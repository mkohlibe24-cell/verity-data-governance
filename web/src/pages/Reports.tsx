import { useQuery } from "@tanstack/react-query";
import type { ColumnDef } from "@tanstack/react-table";
import { Download, FileSpreadsheet, FileText } from "lucide-react";
import { api } from "../lib/session";
import { fmtBytes, fmtInt, fmtNum, fmtTs, fmtUsd } from "../lib/format";
import { DataTable } from "../components/DataTable";
import { Badge, Card, ErrorState, LoadingBlock, PageHeader, RagBadge } from "../components/ui";

type FileRow = { group: string; name: string; path: string; bytes: number; modified: string };
type Run = {
  run_id: string; mode: string; started_at: string; duration_seconds: number; status: string; bronze_rows: number;
  quarantined_rows: number; gold_fact_rows: number; dq_rules_passed: number; dq_rules_evaluated: number; recon_breaks: number;
  alerts: number; open_issues: number;
};
type Reports = {
  files: FileRow[]; runs: Run[]; steps: { step: string; duration_seconds: number; status: string }[];
  manifest: { source: string; file: string; sha256: string; file_bytes: number; records: number; amount_total: number }[];
};

const DESCRIPTIONS: Record<string, string> = {
  "Verity_DQ_Governance_Report.xlsx": "Data Quality & Governance Report: scorecard, rules, issues, KRIs, controls, reconciliation, catalog",
  "dq_scorecard.md": "DQ scorecard by dimension, table and CDE",
  "issue_log.md": "Issue log with owners, due dates and 5-Whys",
  "kri_report.md": "KRI values, thresholds and RAG status",
  "monitoring_results.md": "Monitoring rules, model comparison and threshold choice",
  "data_profile.md": "Data profiling and discovery findings",
  "data_catalog.md": "Data catalog with business definitions and CDEs",
  "lineage.md": "Lineage diagram (Mermaid)",
  "control_inventory.md": "Control inventory: preventive, detective, corrective",
  "data_contracts.md": "Data contract results",
  "pipeline_run_log.csv": "Pipeline run audit log",
};

export default function ReportsPage() {
  const q = useQuery({ queryKey: ["reports"], queryFn: () => api<Reports>("/reports") });
  if (q.isLoading) return <><PageHeader title="Reports" /><LoadingBlock rows={10} /></>;
  if (q.error) return <ErrorState error={q.error} onRetry={q.refetch} />;
  const d = q.data!;
  const excel = d.files.find((f) => f.name.endsWith(".xlsx"));
  const others = d.files.filter((f) => f !== excel);
  const fileCols: ColumnDef<FileRow, any>[] = [
    { accessorKey: "name", header: "File", cell: (c) => (
      <span className="flex items-center gap-2 font-medium whitespace-nowrap"><FileText className="h-4 w-4 text-muted" aria-hidden /><span><span className="font-normal text-muted">{c.row.original.group}/</span>{c.getValue()}</span></span>) },
    { id: "desc", header: "Contents", cell: (c) => <span className="block min-w-[220px] text-xs text-muted">{DESCRIPTIONS[c.row.original.name] ?? ""}</span> },
    { accessorKey: "bytes", header: "Size", cell: (c) => <span className="num whitespace-nowrap">{fmtBytes(c.getValue())}</span> },
    { accessorKey: "modified", header: "Generated", cell: (c) => <span className="num whitespace-nowrap">{fmtTs(c.getValue())}</span> },
    { id: "dl", header: "", cell: (c) => (
      <a href={`/api/reports/file/${c.row.original.path}`} className="inline-flex items-center gap-1 text-xs font-medium whitespace-nowrap text-accent hover:underline" download>
        <Download className="h-3.5 w-3.5" aria-hidden />Download
      </a>) },
  ];
  const runCols: ColumnDef<Run, any>[] = [
    { accessorKey: "run_id", header: "Run", cell: (c) => <span className="font-medium whitespace-nowrap">{c.getValue()}</span> },
    { accessorKey: "mode", header: "Mode" },
    { accessorKey: "status", header: "Status", cell: (c) => <RagBadge rag={c.getValue() === "SUCCESS" ? "PASS" : "FAIL"} /> },
    { accessorKey: "duration_seconds", header: "Duration", cell: (c) => <span className="num">{fmtNum(c.getValue(), 0)} s</span> },
    { accessorKey: "bronze_rows", header: "Bronze rows", cell: (c) => <span className="num">{fmtInt(c.getValue())}</span> },
    { accessorKey: "quarantined_rows", header: "Quarantined", cell: (c) => <span className="num">{fmtInt(c.getValue())}</span> },
    { id: "rules", header: "Rules passed", cell: (c) => <span className="num">{c.row.original.dq_rules_passed} / {c.row.original.dq_rules_evaluated}</span> },
    { accessorKey: "recon_breaks", header: "Recon breaks", cell: (c) => <span className="num">{c.getValue()}</span> },
    { accessorKey: "alerts", header: "Alerts", cell: (c) => <span className="num">{fmtInt(c.getValue())}</span> },
  ];
  return (
    <>
      <PageHeader title="Reports" subtitle="Outputs generated by the pipeline on every full run, the run audit log and the source file manifest." />
      {excel && (
        <Card className="mb-4" bodyClass="flex flex-wrap items-center justify-between gap-4">
          <div className="flex items-center gap-4">
            <div className="flex h-10 w-10 items-center justify-center rounded-md bg-accent-soft text-accent"><FileSpreadsheet className="h-5 w-5" aria-hidden /></div>
            <div>
              <div className="font-semibold">Data Quality &amp; Governance Report</div>
              <div className="text-xs text-muted">{excel.name} · {fmtBytes(excel.bytes)} · generated {fmtTs(excel.modified)}</div>
            </div>
          </div>
          <a href={`/api/reports/file/${excel.path}`} download
            className="inline-flex h-9 items-center gap-2 rounded-md bg-accent px-4 text-sm font-medium text-accent-fg transition-colors duration-150 hover:bg-accent-hover">
            <Download className="h-4 w-4" aria-hidden />Download Excel
          </a>
        </Card>
      )}
      <Card className="mb-4" title={`Generated reports and documentation (${others.length})`}>
        <DataTable data={others} columns={fileCols} pageSize={12} dense />
      </Card>
      <Card className="mb-4" title="Pipeline run audit log">
        <DataTable data={d.runs} columns={runCols} pageSize={8} dense />
      </Card>
      <div className="grid gap-4 xl:grid-cols-2">
        <Card title="Latest run: steps">
          <ol className="grid grid-cols-1 gap-x-6 gap-y-1 text-sm sm:grid-cols-2">
            {d.steps.map((s, i) => (
              <li key={s.step} className="flex items-center justify-between gap-2 border-b border-border py-1.5">
                <span><span className="num mr-2 text-xs text-muted">{i + 1}</span>{s.step}</span>
                <span className="num text-xs text-muted">{fmtNum(s.duration_seconds, 1)} s</span>
              </li>
            ))}
          </ol>
        </Card>
        <Card title="Source file manifest (latest run)" bodyClass="space-y-3">
          {d.manifest.map((m) => (
            <div key={m.file} className="rounded-md border border-border p-3 text-sm">
              <div className="flex items-center justify-between gap-2">
                <span className="font-medium">{m.file}</span><Badge>{m.source}</Badge>
              </div>
              <div className="num mt-1 text-xs text-muted">
                {fmtInt(m.records)} records · {fmtUsd(m.amount_total)} · {fmtBytes(m.file_bytes)}
              </div>
              <div className="mt-1 truncate font-mono text-xs text-muted" title={m.sha256}>SHA-256 {m.sha256}</div>
            </div>
          ))}
        </Card>
      </div>
    </>
  );
}
